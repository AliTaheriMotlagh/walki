'use strict';

// Vercel build step: writes public/config.js so the static app knows where the
// signalling server runs. Set WALKI_SIGNAL_URL to e.g. https://walki-signal.onrender.com

const fs = require('fs');
const path = require('path');

const raw = (process.env.WALKI_SIGNAL_URL || '').trim().replace(/\/+$/, '');
let url = '';
if (raw) {
  url = /^(https?|wss?):\/\//.test(raw) ? raw.replace(/^http/, 'ws') : `wss://${raw}`;
  if (!url.endsWith('/ws')) url += '/ws';
}

fs.writeFileSync(
  path.join(__dirname, '..', 'public', 'config.js'),
  `// Generated by scripts/build-config.js. Empty = same host as the page.\nwindow.WALKI_SIGNAL_URL = ${JSON.stringify(url)};\n`
);
console.log(url ? `signalling server: ${url}` : 'WALKI_SIGNAL_URL not set: app will use its own host for signalling');
